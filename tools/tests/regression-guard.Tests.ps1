# regression-guard.Tests.ps1 -- F001 Task-05: AC-005 normal-mode contract (golden regression).
$ErrorActionPreference = 'Stop'
$tools = Split-Path -Parent $PSScriptRoot
$audit = Join-Path $tools 'skill-audit.ps1'
$report = Join-Path $tools 'skill-audit-report.md'
$golden = Join-Path $PSScriptRoot 'golden-normal-report.txt'

Describe 'AC-005 normal-mode contract (golden regression)' {
    It 'sections 1-5 + verdict are byte-identical with the pre-change baseline' {
        powershell -NoProfile -ExecutionPolicy Bypass -File $audit | Out-Null
        $LASTEXITCODE | Should Be 0
        $new = @([IO.File]::ReadAllLines($report) | Where-Object { $_ -notmatch '^_generated by ' })
        $cut = @()
        foreach ($l in $new) {
            if ($l -match '^## 6\.') { break }
            $cut += $l
        }
        $cut.Count | Should BeGreaterThan 0
        $gold = @([IO.File]::ReadAllLines($golden))
        ($cut -join "`n") | Should Be ($gold -join "`n")
    }

    It 'section 6 exists, real library clean, verdict line format unchanged' {
        $text = [IO.File]::ReadAllText($report)
        $text | Should Match 'Duplicate definitions: 0'
        $text | Should Match 'Verdict: \*\*CLEAN\*\* -- refs checked: 61 \(broken: 0\), assets missing: 0, singular spec/ paths: 0, mudules missing tree: 0'
    }

    It 'a planted dup in a sandbox flips the normal-mode audit exit code to 1' {
        $fx = Join-Path ([IO.Path]::GetTempPath()) "gold-dup-$(Get-Random)"
        $norm = '本行包含必须这一规范标记词，并且整行长度明显超过四十个字符上限，以便稳定命中双定义检测机制。'
        try {
            New-Item -ItemType Directory -Path (Join-Path $fx 'skills\alpha'), (Join-Path $fx 'skills\beta') -Force | Out-Null
            [IO.File]::WriteAllLines((Join-Path $fx 'skills\alpha\SKILL.md'), @('# alpha', $norm))
            [IO.File]::WriteAllLines((Join-Path $fx 'skills\beta\SKILL.md'), @('# beta', $norm))
            powershell -NoProfile -ExecutionPolicy Bypass -File $audit -ScanRoot $fx | Out-Null
            $LASTEXITCODE | Should Be 1
        } finally { Remove-Item -Recurse -Force $fx -ErrorAction SilentlyContinue }
    }
}
